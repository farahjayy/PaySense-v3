"""Check the served band table on students nobody has looked at (ml-audit M2, WP16 follow-up):

    cd backend && uv run python -m ml.engine1_eval.band_fresh_check

The v2 table (`backend/models/engine1/rules/v2/band_inflation.json`) was fitted on 300 students
and checked on the 60 held-out Engine 1 test students; one design choice (dropping the
"never smaller for shorter histories" rule) was made after seeing that held-out check, so those
60 are no longer an untouched test. This script draws a FRESH group from the same pool as the
development students (cohort indices 4,000-9,999, not divisible by ten, so never in Engine 2's
lockbox and never used by the Engine 1 evaluation) that excludes every development student, and
reports the served table's coverage on it beside the v2 rule (one factor of 1.5). It fits
nothing and changes nothing that is served.

Writes `reports/engine1/band_fresh_check.md`.
"""

import argparse
from collections.abc import Sequence
from pathlib import Path

import numpy as np

from app.engines.forecasting.bands import load_band_rule
from app.engines.forecasting.onnx_model import load_served
from ml.engine1_eval.band_calibration import (
    BUCKETS,
    COHORT,
    DEV_PROFILES,
    EVAL_POOL,
    RULE_FILE,
    SEED,
    TARGET,
    Record,
    _table_rows,
    collect,
    dev_profiles,
)
from ml.engine1_eval.loaders.synthetic import DEFAULT_PATH

ROOT = Path(__file__).resolve().parents[3]
REPORT = ROOT / "reports" / "engine1" / "band_fresh_check.md"
FRESH_PROFILES = 300


def fresh_profiles(count: int = FRESH_PROFILES, seed: int = SEED) -> list[int]:
    """Same pool as the development students, none of them, a different seeded draw."""
    used = set(dev_profiles(DEV_PROFILES, seed))
    pool = [i for i in range(EVAL_POOL, COHORT) if i % 10 != 0 and i not in used]
    rng = np.random.default_rng(seed + 3)
    return sorted(int(i) for i in rng.choice(pool, size=count, replace=False))


def served_factor(record: Record) -> float:
    """The v2 table's factor (the table this check was run for; engine v3 is in band_v3.md)."""
    return load_band_rule(RULE_FILE).factor(record.weeks, record.kind)


def render(records: Sequence[Record], ids: Sequence[int]) -> str:
    header = [
        "| series | weeks of history | origins | inside P10-P90, v2 (x1.5) | served factor | "
        "inside P10-P90, served |",
        "|---|---|---|---|---|---|",
    ]
    return "\n".join(
        [
            "# Band calibration: a fresh check of the served table (ml-audit M2)",
            "",
            "> Generated by `python -m ml.engine1_eval.band_fresh_check` - do not edit by hand.",
            "",
            f"{len(ids)} fresh synthetic students: cohort indices {EVAL_POOL}-{COHORT - 1}, not "
            "divisible by ten (never in Engine 2's lockbox, never used by the Engine 1 evaluation),"
            " and none of the 300 development students the table was fitted on. Nothing was "
            "fitted or chosen on them. The table is the one served "
            "(`backend/models/engine1/rules/v2/band_inflation.json`); *inside P10-P90* should be "
            f"{TARGET:.2f}. Buckets start at {', '.join(str(b) for b in BUCKETS)} weeks.",
            "",
            *header,
            *_table_rows(records, served_factor),
            "",
            "Read with `band_calibration.md`: where this check and the held-out check agree, the "
            "choice made after seeing the held-out students did not flatter the table.",
            "",
        ]
    )


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Check the served band table on fresh students.")
    parser.add_argument("--synthetic", type=Path, default=DEFAULT_PATH)
    parser.add_argument("--profiles", type=int, default=FRESH_PROFILES)
    parser.add_argument("--out-report", type=Path, default=REPORT)
    args = parser.parse_args(argv)
    ids = fresh_profiles(args.profiles)
    records = collect(args.synthetic, ids, load_served(), SEED + 4)
    args.out_report.write_text(render(records, ids), encoding="utf-8", newline="\n")
    print(f"wrote {args.out_report}")  # noqa: T201


if __name__ == "__main__":
    main()
