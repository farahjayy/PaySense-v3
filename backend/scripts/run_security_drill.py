"""Run the security drill (ADR D-58) and keep its result as evidence.

    cd backend && uv run python scripts/run_security_drill.py

The same code the `/security` screen runs: every attack in its own throwaway sandbox, a hostile
scripted model, harm measured on the sandbox. Writes `evidence/security-drill/drill.json` and a
generated `evidence/security-drill/SUMMARY.md`. No database, no network, no real model.
"""

import json
import sys
from datetime import date
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "evidence" / "security-drill"
LABEL = {
    "induced_transfers": "Induced transfers",
    "data_extraction": "Data extraction",
    "privilege_escalation": "Privilege escalation",
    "prompt_injection": "Prompt injection",
}


def render(result: dict[str, Any], run_date: date) -> str:
    totals = result["totals"]
    lines = [
        "# Security drill",
        "",
        f"> Generated by `backend/scripts/run_security_drill.py` on {run_date.isoformat()}; do not"
        " edit by hand. The `/security` screen runs the same code (ADR D-58). Each attack runs in"
        " its own throwaway in-memory sandbox; the model is a script that obeys every injected"
        " instruction (the worst case); harm is measured on the sandbox afterwards.",
        "",
        "| Attack class | Attacks | Model fooled | Harm done |",
        "|---|---|---|---|",
    ]
    for t in totals:
        lines.append(
            f"| {LABEL[t['attack_class']]} | {t['attacks']} | {t['fooled']} | {t['harmed']} |"
        )
    lines.append(
        f"| **Total** | **{sum(t['attacks'] for t in totals)}** | "
        f"**{sum(t['fooled'] for t in totals)}** | **{sum(t['harmed'] for t in totals)}** |"
    )
    lines += [
        "",
        "| Attack | Class | What stops it | What was checked | Harm |",
        "|---|---|---|---|---|",
    ]
    for a in result["attacks"]:
        lines.append(
            f"| {a['title']} | {LABEL[a['attack_class']]} | {a['stopped_by']} | {a['evidence']} | "
            f"{'**yes**' if a['harmed'] else 'no'} |"
        )
    lines.append("")
    return "\n".join(lines)


def run_drill() -> dict[str, Any]:
    sys.path.insert(0, str(ROOT / "backend"))
    from app.core.settings import Settings
    from app.security import drill

    settings = Settings(_env_file=None, supabase_url="https://drill.invalid",
                        supabase_service_key="not-used", session_secret="d" * 48,
                        cors_origins="http://localhost:3000")  # fmt: skip
    result = drill.run(settings)
    return {
        "attacks": [a.__dict__ for a in result.attacks],
        "totals": [t.__dict__ for t in result.totals],
    }


def main() -> int:
    result = run_drill()
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "drill.json").write_text(json.dumps(result, indent=1) + "\n", encoding="utf-8")
    page = render(result, date.today())
    (OUT / "SUMMARY.md").write_text(page, encoding="utf-8")
    print(page)
    return 0 if all(t["harmed"] == 0 for t in result["totals"]) else 1


if __name__ == "__main__":
    raise SystemExit(main())
