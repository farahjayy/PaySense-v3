"""Run every check a contributor runs and keep the outputs as evidence (WP9).

    cd backend && uv run python scripts/collect_test_evidence.py

Writes `evidence/tests/<check>.txt` (the tail of each command's output, unedited) and a
generated `evidence/tests/SUMMARY.md` with each command, its exit code and its result line.
Playwright needs the bundled Chromium path in PW_CHROMIUM_PATH where the default download is not
available. A check that cannot run is recorded with its exit code, never as passed.
"""

import os
import re
import subprocess
import sys
import time
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "evidence" / "tests"
KEEP_LINES = 80

CHECKS: list[tuple[str, str, list[str]]] = [
    ("backend-ruff", "backend", ["uv", "run", "ruff", "check", "."]),
    ("backend-format", "backend", ["uv", "run", "ruff", "format", "--check", "."]),
    ("backend-pytest", "backend",
     ["uv", "run", "pytest", "-q", "-p", "no:cacheprovider", "--cov=app", "--cov-report=term"]),
    ("frontend-lint", "frontend", ["npm", "run", "lint"]),
    ("frontend-tsc", "frontend", ["npx", "tsc", "--noEmit"]),
    ("frontend-api-types", "frontend", ["npm", "run", "check:api"]),
    ("frontend-vitest", "frontend", ["npx", "vitest", "run", "--coverage"]),
    ("frontend-build", "frontend", ["npm", "run", "build"]),
    ("frontend-playwright", "frontend", ["npx", "playwright", "test"]),
]  # fmt: skip

RESULT = re.compile(
    r"(\d+ passed[^\n]*|Tests\s+\d+ passed[^\n]*|All checks passed!|\d+ files? already formatted|"
    r"Compiled successfully[^\n]*|matches the backend OpenAPI document|TOTAL\s+\d+\s+\d+\s+\d+%|"
    r"All files\s*\|[^\n]*|\d+ failed[^\n]*|error[^\n]*)",
    re.IGNORECASE,
)


def result_lines(output: str) -> list[str]:
    """The lines that say how a check ended: counts, totals, coverage, errors."""
    found = [m.group(1).strip() for m in RESULT.finditer(output)]
    return list(dict.fromkeys(found))[-4:]


def run_check(name: str, folder: str, cmd: list[str]) -> dict[str, object]:
    start = time.perf_counter()
    try:
        done = subprocess.run(  # noqa: S603
            cmd, cwd=ROOT / folder, capture_output=True, text=True, timeout=3600, env=os.environ
        )
        output, code = done.stdout + done.stderr, done.returncode
    except (OSError, subprocess.TimeoutExpired) as err:
        output, code = f"could not run: {err}", -1
    seconds = time.perf_counter() - start
    tail = "\n".join(output.splitlines()[-KEEP_LINES:])
    (OUT / f"{name}.txt").write_text(f"$ {' '.join(cmd)}  (in {folder}/)\n{tail}\n", "utf-8")
    return {"name": name, "cmd": f"cd {folder} && {' '.join(cmd)}", "code": code,
            "seconds": round(seconds), "result": result_lines(output)}  # fmt: skip


def render(rows: list[dict[str, object]]) -> str:
    lines = [
        "# Test evidence",
        "",
        f"> Generated by `backend/scripts/collect_test_evidence.py` on {date.today().isoformat()}; "
        "do not edit by hand. Each check's output (last lines) is in the `.txt` file beside this.",
        "",
        "| Check | Command | Exit | s | Result |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        result = "; ".join(str(x) for x in r["result"]).replace("|", "/") or "-"  # type: ignore[union-attr]
        lines.append(f"| {r['name']} | `{r['cmd']}` | {r['code']} | {r['seconds']} | {result} |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    only = set(sys.argv[1:])
    rows = [run_check(*c) for c in CHECKS if not only or c[0] in only]
    (OUT / "SUMMARY.md").write_text(render(rows), encoding="utf-8")
    print(render(rows))
    return 0 if all(r["code"] == 0 for r in rows) else 1


if __name__ == "__main__":
    sys.exit(main())
