"""Run the security scans and keep their outputs as evidence (WP8).

    cd backend && uv run python scripts/run_security_scans.py

Writes to `evidence/scans/`:
  pip-audit-runtime.json   the backend's runtime dependencies (what the server runs)
  pip-audit-all.json       runtime + dev + ml groups
  npm-audit-prod.json      the frontend's production dependencies
  npm-audit-all.json       every frontend dependency, dev tools included
  gitleaks.json            a secret scan of the whole git history (findings redacted)
  SUMMARY.md               the counts, generated from the files above

Needs `uvx` (pip-audit), `npm`, and `gitleaks` on PATH or in $GITLEAKS. A scanner that cannot run
is recorded as not run, never as clean.
"""

import json
import os
import shutil
import subprocess
import sys
import tempfile
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "evidence" / "scans"


def _run(cmd: list[str], cwd: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=900)  # noqa: S603


def pip_audit(groups: list[str], name: str) -> str:
    args = ["uv", "export", "--format", "requirements-txt", "--no-hashes", "--no-emit-project"]
    args += ["--no-default-groups"] + [f"--group={g}" for g in groups]
    exported = _run(args, ROOT / "backend")
    if exported.returncode != 0:
        return f"not run (uv export failed: {exported.stderr.strip()[:200]})"
    with tempfile.NamedTemporaryFile("w", suffix=".txt", delete=False) as handle:
        handle.write(exported.stdout)
        requirements = handle.name
    # the pinned versions are audited as written (no install): the CPU torch wheel is not on PyPI
    audit = ["uvx", "pip-audit", "-r", requirements, "--no-deps", "--disable-pip"]
    audit += ["--format", "json"]
    result = _run(audit, ROOT / "backend")
    os.unlink(requirements)
    try:
        data = json.loads(result.stdout)
    except json.JSONDecodeError:
        return "not run (pip-audit: " + " ".join(result.stderr.split())[:200] + ")"
    (OUT / f"{name}.json").write_text(json.dumps(data, indent=1) + "\n", encoding="utf-8")
    deps = data.get("dependencies", [])
    vulns = [(d["name"], v["id"]) for d in deps for v in d.get("vulns", [])]
    listed = ", ".join(f"{n} {i}" for n, i in vulns) or "none"
    return f"{len(deps)} packages audited, {len(vulns)} known vulnerabilities ({listed})"


def npm_audit(prod: bool, name: str) -> str:
    cmd = ["npm", "audit", "--json"] + (["--omit=dev"] if prod else [])
    result = _run(cmd, ROOT / "frontend")
    try:
        data = json.loads(result.stdout)
    except json.JSONDecodeError:
        return f"not run (npm audit: {result.stderr.strip()[:200]})"
    (OUT / f"{name}.json").write_text(json.dumps(data, indent=1) + "\n", encoding="utf-8")
    counts = data.get("metadata", {}).get("vulnerabilities", {})
    names = sorted(data.get("vulnerabilities", {}))
    tail = f" ({', '.join(names)})" if names else ""
    return ", ".join(f"{k} {v}" for k, v in counts.items()) + tail


def gitleaks() -> str:
    binary = os.environ.get("GITLEAKS") or shutil.which("gitleaks")
    if not binary:
        return "not run (gitleaks not installed)"
    report = OUT / "gitleaks.json"
    result = _run(
        [binary, "detect", "--source", str(ROOT), "--redact", "--report-format", "json",
         "--report-path", str(report), "--no-banner"],
        ROOT,
    )  # fmt: skip
    if not report.exists():
        return f"not run (gitleaks: {result.stderr.strip()[:200]})"
    findings = json.loads(report.read_text(encoding="utf-8") or "[]")
    rules = sorted({f.get("RuleID", "?") for f in findings})
    where = sorted({f.get("File", "?") for f in findings})
    detail = f" (rules {rules}; files {where})" if findings else ""
    return f"{len(findings)} findings over the full history{detail}"


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    rows = [
        ("pip-audit, backend runtime", pip_audit([], "pip-audit-runtime")),
        ("pip-audit, backend runtime + dev + ml", pip_audit(["dev", "ml"], "pip-audit-all")),
        ("npm audit, frontend production", npm_audit(True, "npm-audit-prod")),
        ("npm audit, frontend all (dev tools included)", npm_audit(False, "npm-audit-all")),
        ("gitleaks, whole git history", gitleaks()),
    ]
    lines = [
        "# Security scans",
        "",
        f"> Generated by `backend/scripts/run_security_scans.py` on {date.today().isoformat()}; "
        "do not edit by hand. Raw outputs are the JSON files beside this one.",
        "",
        "| Scan | Result |",
        "|---|---|",
        *[f"| {name} | {result} |" for name, result in rows],
        "",
    ]
    (OUT / "SUMMARY.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
